def _row_level_security() -> None:
    # No FORCE: the owner (cm_owner) bypasses RLS; cm_app is not the owner, so it never does.
    for table in ("tenants", "tenant_memberships", "projects", "role_bindings", "audit_logs"):
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")

    is_member = (
        "EXISTS (SELECT 1 FROM tenant_memberships m WHERE m.tenant_id = tenants.id"
        f" AND {_user_ok('m.user_id')})"
    )
    _policy("tenants", "tenants_read", "SELECT", f"{_tenant_ok('id')} OR {is_member}", None)
    _policy("tenants", "tenants_write", "ALL", _tenant_ok("id"), _tenant_ok("id"))

    # a user always sees their own memberships/bindings (to list tenants, resolve permissions)
    for table in ("tenant_memberships", "role_bindings"):
        _policy(
            table, f"{table}_read", "SELECT",
            f"{_tenant_ok('tenant_id')} OR {_user_ok('user_id')}", None,
        )
        _policy(table, f"{table}_write", "ALL", _tenant_ok("tenant_id"), _tenant_ok("tenant_id"))

    _policy("projects", "projects_isolation", "ALL", _tenant_ok("tenant_id"), _tenant_ok("tenant_id"))

    # anyone may append (e.g. LOGIN_FAILED has no tenant); reading is tenant-scoped
    _policy("audit_logs", "audit_logs_read", "SELECT", _tenant_ok("tenant_id"), None)
    _policy("audit_logs", "audit_logs_append", "INSERT", None, "true")


