PLATFORM = "current_setting('app.platform_scope', true) = 'on'"


def _tenant_ok(col: str) -> str:
    return (
        f"({PLATFORM} OR {col} = ANY "
        "(string_to_array(current_setting('app.tenant_ids', true), ',')::uuid[]))"
    )


def _user_ok(col: str) -> str:
    # compared as text: '' (setting reset after a previous transaction) is not a valid uuid
    return f"({col}::text = current_setting('app.user_id', true))"


